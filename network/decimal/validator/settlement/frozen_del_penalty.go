// FrozenDELPenaltyProof carries the exact amount, cursor and hold timing for
// one unmatured claim. An ineligible claim advances its cursor without loss.
type FrozenDELPenaltyProof struct {
	Index                       common.Hash
	BeforeCursor, AfterCursor   common.Hash
	Remaining, Burned           sdkmath.Int
	InfractionHeight            int64
	HoldStartTime, HoldDeadline int64
	Eligible                    bool
}

type frozenDELPenaltyKey struct{}
type frozenDELPenaltyCall struct {
	executor *Executor
	height   int64
	data     []byte
}

// AuthorizeFrozenDELPenalty accepts only the internal call generated by the
// executor after it has matched a frozen DEL position and checkpoint.
func (e *Executor) AuthorizeFrozenDELPenalty(ctx sdk.Context, msg core.Message) bool {
	call, ok := ctx.Value(frozenDELPenaltyKey{}).(frozenDELPenaltyCall)
	return ok && e != nil && call.executor == e && call.height == ctx.BlockHeight() &&
		ctx.ExecMode() == sdk.ExecModeFinalize && msg.From == masterPenaltySender() &&
		msg.To != nil && *msg.To == e.roles.Gateway && msg.Value != nil && msg.Value.Sign() == 0 &&
		len(msg.SetCodeAuthorizations) == 0 && bytes.Equal(call.data, msg.Data)
}

// ApplyFrozenDELPenalty realizes or checkpoints exactly one announced
// penalty, then commits only after the caller reconciles the native queue.
func (e *Executor) ApplyFrozenDELPenalty(ctx sdk.Context, row validatortypes.EVMFrozenBinding, infractionHeight int64, percentage uint16,
	nativeSupply func(sdk.Context) sdkmath.Int, project func(sdk.Context, FrozenDELPenaltyProof) error,
) error {
	if nativeSupply == nil || project == nil || ctx.ExecMode() != sdk.ExecModeFinalize ||
		infractionHeight <= 0 || infractionHeight > ctx.BlockHeight() || percentage == 0 || percentage > 100 {
		return errors.New("frozen DEL penalty requires finalized block, approved infraction, supply and queue projection")
	}
	index, _, err := e.withdrawalIdentity(row)
	if err != nil {
		return err
	}
	now := ctx.BlockTime().Unix()
	target := row.NativeTarget.StakeType
	if !row.Active || row.SourceKind != validatortypes.EVMStakeBindingKind_EVM_STAKE_BINDING_COIN ||
		(target != validatortypes.StakeType_Coin && target != validatortypes.StakeType_CoinHold) || row.CreatedHeight <= 0 ||
		row.UpdatedHeight > ctx.BlockHeight() || now <= 0 ||
		common.BytesToHash(row.CompletionTimestamp).Big().Cmp(big.NewInt(now)) <= 0 {
		return errors.New("penalty requires an unmatured frozen DEL binding")
	}
	child, write := ctx.CacheContext()
	validator := common.BytesToAddress(row.SourceValidator)
	source, err := e.authenticatePenaltySource(child, validator, percentage)
	if err != nil {
		return err
	}
	sender := masterPenaltySender()
	if err := e.requireInert(child, sender); err != nil {
		return err
	}
	before, err := e.readFrozen(child, index)
	if err != nil {
		return err
	}
	asset, err := e.matchFrozen(before, row, statusFrozen)
	if err != nil {
		return err
	}
	holdStart, holdDeadline, err := frozenDELPenaltyTiming(before, target, now)
	if err != nil {
		return err
	}
	checkpoint, err := e.readFrozenDELCheckpoint(child, index)
	if err != nil {
		return err
	}
	if checkpoint.creationHeight != common.BigToHash(big.NewInt(row.CreatedHeight)) {
		return errors.New("frozen DEL checkpoint differs from native creation height")
	}
	next := new(big.Int).Add(checkpoint.cursor.Big(), big.NewInt(1))
	if next.BitLen() > 256 {
		return errors.New("frozen DEL penalty cursor overflow")
	}
	afterCursor := common.BigToHash(next)
	status, err := e.verifyAnnouncedPenalty(child, validator, checkpoint.cursor, afterCursor, percentage)
	if err != nil {
		return err
	}
	beforeState, err := e.readFrozenDELPenaltyBalances(child, validator, asset, nativeSupply)
	if err != nil {
		return err
	}
	if beforeState.wrapped.Cmp(row.RawAmount.BigInt()) < 0 {
		return errors.New("Gateway WDEL is below the frozen DEL claim")
	}
	eligible := row.CreatedHeight >= infractionHeight
	burned := new(big.Int)
	if eligible {
		burned.Mul(row.RawAmount.BigInt(), new(big.Int).SetUint64(uint64(percentage)))
		burned.Quo(burned, big.NewInt(100))
	}
	loss := sdkmath.NewIntFromBigInt(burned)
	remaining := row.RawAmount.Sub(loss)
	data, err := e.gateway.Pack("applyFrozenDELPenalty", index.Big(), big.NewInt(infractionHeight), row.RawAmount.BigInt(), checkpoint.cursor.Big())
	if err != nil {
		return err
	}
	authorized := child.WithValue(frozenDELPenaltyKey{}, frozenDELPenaltyCall{executor: e, height: child.BlockHeight(), data: bytes.Clone(data)})
	result, err := e.invokePenalty(authorized, sender, e.roles.Gateway, data)
	if err != nil {
		return err
	}
	if len(result.Ret) != 0 {
		return errors.New("Gateway frozen DEL penalty returned unexpected data")
	}
	proof := FrozenDELPenaltyProof{Index: index, BeforeCursor: checkpoint.cursor, AfterCursor: afterCursor,
		Remaining: remaining, Burned: loss, InfractionHeight: infractionHeight,
		HoldStartTime: holdStart, HoldDeadline: holdDeadline, Eligible: eligible}
	receipt := &ethtypes.Receipt{Status: ethtypes.ReceiptStatusSuccessful, Logs: evmtypes.LogsToEthereum(result.Logs)}
	if err := e.verifyFrozenDELPenaltyLogs(receipt, row.RawAmount, proof); err != nil {
		return err
	}
	after, err := e.readFrozen(child, index)
	if err != nil {
		return err
	}
	before[3] = common.BigToHash(remaining.BigInt())
	if remaining.IsZero() {
		before[freezeStatusWord] = smallWord(statusCompleted)
	}
	if before != after {
		return errors.New("Gateway changed immutable frozen fields or recorded the wrong penalty amount")
	}
	recorded, err := e.readFrozenDELCheckpoint(child, index)
	if err != nil {
		return err
	}
	if recorded.creationHeight != checkpoint.creationHeight || recorded.cursor != afterCursor {
		return errors.New("Gateway frozen DEL checkpoint did not advance exactly once")
	}
	afterState, err := e.readFrozenDELPenaltyBalances(child, validator, asset, nativeSupply)
	if err != nil {
		return err
	}
	if !bytes.Equal(beforeState.reserve, afterState.reserve) || afterState.wrapped.Cmp(remaining.BigInt()) < 0 {
		return errors.New("frozen DEL penalty changed active reserve or left the claim without WDEL")
	}
	if err := verifyDELBurnDeltas(beforeState.payoutState, afterState.payoutState, beforeState.bankSupply, afterState.bankSupply, burned); err != nil {
		return err
	}
	if err := e.confirmPenaltySource(child, source); err != nil {
		return err
	}
	afterStatus, err := e.verifyAnnouncedPenalty(child, validator, checkpoint.cursor, afterCursor, percentage)
	if err != nil {
		return err
	}
	if afterStatus != status {
		return errors.New("Master validator status changed during frozen DEL penalty")
	}
	if err := project(child, proof); err != nil {
		return fmt.Errorf("project frozen DEL penalty: %w", err)
	}
	write()
	return nil
}

func frozenDELPenaltyTiming(words frozenWords, target validatortypes.StakeType, now int64) (start, deadline int64, err error) {
	if target == validatortypes.StakeType_Coin && words[6] == (common.Hash{}) && words[7] == (common.Hash{}) {
		return 0, 0, nil
	}
	if target == validatortypes.StakeType_CoinHold {
		since, until := words[7].Big(), words[6].Big()
		if since.IsInt64() && until.IsInt64() && since.Sign() > 0 && until.Cmp(since) > 0 && until.Int64() < now {
			return since.Int64(), until.Int64(), nil
		}
	}
	return 0, 0, errors.New("frozen DEL penalty timing differs from its native target or hold has not expired")
}

type frozenDELCheckpoint struct {
	creationHeight, cursor common.Hash
}

func (e *Executor) readFrozenDELCheckpoint(ctx sdk.Context, index common.Hash) (frozenDELCheckpoint, error) {
	out, err := e.read(ctx, e.roles.Gateway, e.gateway, "getFrozenDELCheckpoint", 2*common.HashLength, index.Big())
	if err != nil {
		return frozenDELCheckpoint{}, err
	}
	return frozenDELCheckpoint{creationHeight: common.BytesToHash(out[:common.HashLength]), cursor: common.BytesToHash(out[common.HashLength:])}, nil
}

type frozenDELPenaltyBalances struct {
	payoutState
	reserve    []byte
	bankSupply *big.Int
}

func (e *Executor) readFrozenDELPenaltyBalances(ctx sdk.Context, validator common.Address, asset payout,
	nativeSupply func(sdk.Context) sdkmath.Int,
) (frozenDELPenaltyBalances, error) {
	state, err := e.payoutState(ctx, asset, common.Address{})
	if err != nil {
		return frozenDELPenaltyBalances{}, err
	}
	reserve, err := e.read(ctx, e.roles.Gateway, e.gateway, "getValidatorReserve", 2*common.HashLength, validator, e.roles.WrappedDEL)
	if err != nil {
		return frozenDELPenaltyBalances{}, err
	}
	supply := nativeSupply(ctx)
	if supply.IsNil() || supply.IsNegative() {
		return frozenDELPenaltyBalances{}, errors.New("invalid native bank supply for frozen DEL penalty")
	}
	return frozenDELPenaltyBalances{payoutState: state, reserve: reserve, bankSupply: supply.BigInt()}, nil
}

func (e *Executor) verifyFrozenDELPenaltyLogs(receipt *ethtypes.Receipt, before sdkmath.Int, proof FrozenDELPenaltyProof) error {
	markers, err := e.completions(receipt)
	if err != nil {
		return err
	}
	expected := 1
	if proof.Burned.IsPositive() {
		expected += 2
	}
	if proof.Remaining.IsZero() {
		expected++
	}
	if len(markers) != 0 || len(receipt.Logs) != expected {
		return errors.New("unexpected log count for one frozen DEL penalty")
	}
	logs := receipt.Logs
	if proof.Burned.IsPositive() {
		if err := e.verifyDELBurnLogs(logs[:2], proof.Burned.BigInt()); err != nil {
			return err
		}
		logs = logs[2:]
	}
	applied := e.gateway.Events["FrozenDELPenaltyApplied"]
	data, err := applied.Inputs.NonIndexed().Pack(big.NewInt(proof.InfractionHeight), before.BigInt(), proof.Remaining.BigInt(), proof.Eligible)
	if err != nil {
		return err
	}
	if !matchFrozenDELPenaltyLog(logs[0], e.roles.Gateway, applied.ID, proof, data) {
		return errors.New("Gateway did not emit the exact frozen DEL penalty")
	}
	if proof.Remaining.IsZero() &&
		!matchFrozenDELPenaltyLog(logs[1], e.roles.Gateway, e.gateway.Events["FrozenDELClaimExtinguished"].ID, proof, nil) {
		return errors.New("Gateway did not emit the exact zero frozen claim event")
	}
	return nil
}

func matchFrozenDELPenaltyLog(log *ethtypes.Log, gateway common.Address, topic common.Hash, proof FrozenDELPenaltyProof, data []byte) bool {
	return log.Address == gateway && len(log.Topics) == 3 && log.Topics[0] == topic &&
		log.Topics[1] == proof.Index && log.Topics[2] == proof.AfterCursor && bytes.Equal(log.Data, data)
}
