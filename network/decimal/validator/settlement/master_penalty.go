// MasterPenaltyProof identifies one verified append and its old and new
// penalty counts. The append pauses the validator without burning funds.
type MasterPenaltyProof struct {
	Validator                 common.Address
	Percentage                uint16
	BeforeCursor, AfterCursor common.Hash
}

type masterPenaltyKey struct{}
type masterPenaltyCall struct {
	executor   *Executor
	height     int64
	validator  common.Address
	percentage uint16
}

type penaltySourceKey struct{}

type penaltySourceScope struct {
	executor   *Executor
	height     int64
	validator  common.Address
	percentage uint16
	active     bool
}

// Each realization still verifies its exact Master entry, receipt and
// balance deltas. Within an append, authenticate the shared roles at both
// ends of the same outer cache instead of repeating that read per position.
func (e *Executor) authenticatePenaltySource(ctx sdk.Context, validator common.Address, percentage uint16) (*evmview.StakeSource, error) {
	if scope, ok := ctx.Value(penaltySourceKey{}).(*penaltySourceScope); ok {
		if !scope.active || scope.executor != e || scope.height != ctx.BlockHeight() ||
			scope.validator != validator || scope.percentage != percentage {
			return nil, errors.New("position penalty differs from the active Master reconciliation scope")
		}
		return nil, nil
	}
	source, err := e.auth.AuthenticateStakeProfile(ctx)
	if err != nil {
		return nil, err
	}
	return &source, nil
}

func (e *Executor) confirmPenaltySource(ctx sdk.Context, before *evmview.StakeSource) error {
	if before == nil {
		return nil
	}
	after, err := e.auth.AuthenticateStakeProfile(ctx)
	if err != nil {
		return err
	}
	if after != *before {
		return errors.New("authenticated system roles changed during penalty reconciliation")
	}
	return nil
}

func masterPenaltySender() common.Address {
	return common.BytesToAddress(authtypes.NewModuleAddress(govtypes.ModuleName))
}

// AuthorizeMasterPenalty checks only the exact call generated by the
// AppendMasterPenalty child context. It confers no other governance authority.
func (e *Executor) AuthorizeMasterPenalty(ctx sdk.Context, msg core.Message) bool {
	call, ok := ctx.Value(masterPenaltyKey{}).(masterPenaltyCall)
	if !ok || e == nil || call.executor != e || call.height != ctx.BlockHeight() ||
		ctx.ExecMode() != sdk.ExecModeFinalize || msg.From != masterPenaltySender() ||
		msg.To == nil || *msg.To != e.roles.MasterValidator || msg.Value == nil ||
		msg.Value.Sign() != 0 || len(msg.SetCodeAuthorizations) != 0 {
		return false
	}
	data, err := e.master.Pack("addPenalty", call.validator, call.percentage)
	return err == nil && bytes.Equal(data, msg.Data)
}

// AppendMasterPenalty makes a single Master announcement and calls reconcile
// in the same child cache. Only the authenticated genesis governance owner
// may append. The caller must reconcile all active and frozen liabilities
// and validator eligibility in the callback before making this append durable.
func (e *Executor) AppendMasterPenalty(ctx sdk.Context, validator common.Address, percentage uint16,
	nativeSupply func(sdk.Context) sdkmath.Int, reconcile func(sdk.Context, MasterPenaltyProof) error,
) error {
	if e == nil || e.evm == nil || nativeSupply == nil || reconcile == nil ||
		ctx.ExecMode() != sdk.ExecModeFinalize || ctx.BlockHeight() <= 0 ||
		validator == (common.Address{}) || percentage == 0 || percentage > 100 {
		return errors.New("Master penalty requires finalized block, validator, approved percentage, supply and reconciliation")
	}
	child, write := ctx.CacheContext()
	source, err := e.auth.AuthenticateStakeProfile(child)
	if err != nil {
		return err
	}
	sender := masterPenaltySender()
	if err := e.requireInert(child, sender); err != nil {
		return err
	}
	state, err := e.read(child, e.roles.MasterValidator, e.master, "getValidatorState", 3*common.HashLength, validator)
	if err != nil {
		return err
	}
	status := common.BytesToHash(state[:common.HashLength])
	if (status != smallWord(1) && status != smallWord(2)) ||
		common.BytesToHash(state[common.HashLength:2*common.HashLength]) != (common.Hash{}) {
		return errors.New("Master penalty requires an unpaused candidate or approved validator")
	}
	beforeCursor := common.BytesToHash(state[2*common.HashLength:])
	next := new(big.Int).Add(beforeCursor.Big(), big.NewInt(1))
	if next.BitLen() > 256 {
		return errors.New("Master penalty count exceeds uint256")
	}
	afterCursor := common.BigToHash(next)
	before, err := e.readMasterPenaltyBalances(child, validator, nativeSupply)
	if err != nil {
		return err
	}
	data, err := e.master.Pack("addPenalty", validator, percentage)
	if err != nil {
		return err
	}
	authorized := child.WithValue(masterPenaltyKey{}, masterPenaltyCall{executor: e, height: child.BlockHeight(), validator: validator, percentage: percentage})
	result, err := e.invokePenalty(authorized, sender, e.roles.MasterValidator, data)
	if err != nil {
		return err
	}
	if len(result.Ret) != 0 {
		return errors.New("Master penalty returned unexpected data")
	}
	receipt := &ethtypes.Receipt{Status: ethtypes.ReceiptStatusSuccessful, Logs: evmtypes.LogsToEthereum(result.Logs)}
	if err := e.verifyMasterPenaltyLogs(receipt, validator, status, percentage); err != nil {
		return err
	}
	afterStatus, err := e.verifyAnnouncedPenalty(child, validator, beforeCursor, afterCursor, percentage)
	if err != nil {
		return err
	}
	if afterStatus != status {
		return errors.New("Master penalty changed the validator status")
	}
	after, err := e.readMasterPenaltyBalances(child, validator, nativeSupply)
	if err != nil {
		return err
	}
	if before.del != after.del || before.wdel != after.wdel || before.wdelSupply != after.wdelSupply ||
		!before.bankSupply.Equal(after.bankSupply) {
		return errors.New("Master penalty announcement changed native DEL or WDEL")
	}
	proof := MasterPenaltyProof{Validator: validator, Percentage: percentage, BeforeCursor: beforeCursor, AfterCursor: afterCursor}
	scope := &penaltySourceScope{executor: e, height: child.BlockHeight(), validator: validator, percentage: percentage, active: true}
	defer func() { scope.active = false }()
	if err := reconcile(child.WithValue(penaltySourceKey{}, scope), proof); err != nil {
		return fmt.Errorf("reconcile announced Master penalty: %w", err)
	}
	scope.active = false
	if err := e.confirmPenaltySource(child, &source); err != nil {
		return err
	}
	write()
	return nil
}

type masterPenaltyBalances struct {
	del, wdel  [5]common.Hash
	wdelSupply common.Hash
	bankSupply sdkmath.Int
}

func (e *Executor) readMasterPenaltyBalances(ctx sdk.Context, validator common.Address,
	nativeSupply func(sdk.Context) sdkmath.Int,
) (masterPenaltyBalances, error) {
	var balances masterPenaltyBalances
	for i, account := range [...]common.Address{validator, masterPenaltySender(), e.roles.MasterValidator, e.roles.Gateway, e.roles.WrappedDEL} {
		del := e.evm.GetBalance(ctx, account)
		if del == nil {
			return balances, errors.New("Master penalty cannot read native DEL balance")
		}
		balances.del[i] = common.BigToHash(del.ToBig())
		wdel, err := e.read(ctx, e.roles.WrappedDEL, e.wrapper, "balanceOf", common.HashLength, account)
		if err != nil {
			return balances, err
		}
		balances.wdel[i] = common.BytesToHash(wdel)
	}
	supply, err := e.read(ctx, e.roles.WrappedDEL, e.wrapper, "totalSupply", common.HashLength)
	if err != nil {
		return balances, err
	}
	balances.wdelSupply = common.BytesToHash(supply)
	balances.bankSupply = nativeSupply(ctx)
	if balances.bankSupply.IsNil() || balances.bankSupply.IsNegative() {
		return balances, errors.New("Master penalty requires valid native DEL supply")
	}
	return balances, nil
}

func (e *Executor) verifyMasterPenaltyLogs(receipt *ethtypes.Receipt, validator common.Address, status common.Hash, percentage uint16) error {
	markers, err := e.completions(receipt)
	if err != nil {
		return err
	}
	if len(markers) != 0 || len(receipt.Logs) != 2 {
		return errors.New("Master penalty requires exactly the pause and append logs")
	}
	identity := common.BytesToHash(validator[:])
	paused := smallWord(1)
	want := append(status.Bytes(), paused[:]...)
	amount := common.BigToHash(new(big.Int).SetUint64(uint64(percentage)))
	for i, expected := range []struct {
		topic common.Hash
		data  []byte
	}{{e.master.Events["ValidatorUpdated"].ID, want}, {e.master.Events["ValidatorPenalty"].ID, amount[:]}} {
		log := receipt.Logs[i]
		if log.Address != e.roles.MasterValidator || len(log.Topics) != 2 ||
			log.Topics[0] != expected.topic || log.Topics[1] != identity || !bytes.Equal(log.Data, expected.data) {
			return errors.New("Master penalty logs differ from the exact pause and append")
		}
	}
	return nil
}
