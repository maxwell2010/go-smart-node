// MasterPenaltyProof identifies one verified append and its old and new
// penalty counts. The append pauses the validator without burning funds.
type MasterPenaltyProof struct {
	Validator                 common.Address
	Percentage                uint16
	InfractionHeight          int64
	BeforeCursor, AfterCursor common.Hash
}

type masterPenaltyKey struct{}
type masterPenaltyCall struct {
	executor *Executor
	height   int64
	proof    MasterPenaltyProof
}

type penaltySourceKey struct{}

type penaltySourceScope struct {
	executor         *Executor
	height           int64
	validator        common.Address
	percentage       uint16
	infractionHeight int64
	active           bool
}

// Each realization still verifies its exact Master entry, receipt and
// balance deltas. Within an append, authenticate the shared roles at both
// ends of the same outer cache instead of repeating that read per position.
func (e *Executor) authenticatePenaltySource(ctx sdk.Context, validator common.Address, percentage uint16) (*evmview.StakeSource, error) {
	if scope, ok := ctx.Value(penaltySourceKey{}).(*penaltySourceScope); ok {
		if !scope.active || scope.infractionHeight != 0 || scope.executor != e || scope.height != ctx.BlockHeight() ||
			scope.validator != validator || scope.percentage != percentage {
			return nil, errors.New("position penalty differs from the active Master reconciliation scope")
		}
		return nil, nil
	}
	source, err := e.auth.AuthenticateStakeProfile(ctx)
	if err != nil {
		return nil, err
	}
	return &source, nil
}

func (e *Executor) confirmPenaltySource(ctx sdk.Context, before *evmview.StakeSource) error {
	if before == nil {
		return nil
	}
	after, err := e.auth.AuthenticateStakeProfile(ctx)
	if err != nil {
		return err
	}
	if after != *before {
		return errors.New("authenticated system roles changed during penalty reconciliation")
	}
	return nil
}

func masterPenaltySender() common.Address {
	return common.BytesToAddress(authtypes.NewModuleAddress(govtypes.ModuleName))
}

// AuthorizeMasterPenalty checks only the exact call generated by the
// AppendMasterPenalty child context. It confers no other governance authority.
func (e *Executor) AuthorizeMasterPenalty(ctx sdk.Context, msg core.Message) bool {
	return e.authorizeMasterPenalty(ctx, msg, false)
}

// AuthorizeMasterHistoricalPenalty is scoped to an exact typed append. An
// application enables this path only with historical settlement in place.
func (e *Executor) AuthorizeMasterHistoricalPenalty(ctx sdk.Context, msg core.Message) bool {
	return e.authorizeMasterPenalty(ctx, msg, true)
}

func (e *Executor) authorizeMasterPenalty(ctx sdk.Context, msg core.Message, historical bool) bool {
	call, ok := ctx.Value(masterPenaltyKey{}).(masterPenaltyCall)
	if !ok || e == nil || call.executor != e || call.height != ctx.BlockHeight() ||
		(call.proof.InfractionHeight != 0) != historical ||
		ctx.ExecMode() != sdk.ExecModeFinalize || msg.From != masterPenaltySender() ||
		msg.To == nil || *msg.To != e.roles.MasterValidator || msg.Value == nil ||
		msg.Value.Sign() != 0 || len(msg.SetCodeAuthorizations) != 0 {
		return false
	}
	data, err := e.packMasterPenalty(call.proof)
	return err == nil && bytes.Equal(data, msg.Data)
}

func (e *Executor) packMasterPenalty(proof MasterPenaltyProof) ([]byte, error) {
	if proof.InfractionHeight == 0 {
		return e.master.Pack("addPenalty", proof.Validator, proof.Percentage)
	}
	return e.master.Pack("appendDuplicateVotePenalty", proof.Validator, proof.BeforeCursor.Big(),
		big.NewInt(proof.InfractionHeight), proof.Percentage)
}

// AppendMasterPenalty makes a single Master announcement and calls reconcile
// in the same child cache. Only the authenticated genesis governance owner
// may append. The caller must reconcile all active and frozen liabilities
// and validator eligibility in the callback before making this append durable.
func (e *Executor) AppendMasterPenalty(ctx sdk.Context, validator common.Address, percentage uint16,
	nativeSupply func(sdk.Context) sdkmath.Int, reconcile func(sdk.Context, MasterPenaltyProof) error,
) error {
	return e.appendMasterPenalty(ctx, MasterPenaltyProof{Validator: validator, Percentage: percentage}, nativeSupply, reconcile)
}

// AppendMasterHistoricalPenalty announces an authenticated duplicate-vote
// height. The caller must realize all historical liabilities before committing.
func (e *Executor) AppendMasterHistoricalPenalty(ctx sdk.Context, validator common.Address, infractionHeight int64,
	nativeSupply func(sdk.Context) sdkmath.Int, reconcile func(sdk.Context, MasterPenaltyProof) error,
) error {
	if infractionHeight <= 0 || infractionHeight >= ctx.BlockHeight() {
		return errors.New("historical Master penalty requires a prior committed infraction height")
	}
	proof := MasterPenaltyProof{Validator: validator, Percentage: validatorkeeper.HistoricalDELPenaltyPercent, InfractionHeight: infractionHeight}
	return e.appendMasterPenalty(ctx, proof, nativeSupply, reconcile)
}

func (e *Executor) appendMasterPenalty(ctx sdk.Context, proof MasterPenaltyProof,
	nativeSupply func(sdk.Context) sdkmath.Int, reconcile func(sdk.Context, MasterPenaltyProof) error,
) error {
	validator, percentage := proof.Validator, proof.Percentage
	historical := proof.InfractionHeight != 0
	if e == nil || e.evm == nil || nativeSupply == nil || reconcile == nil ||
		ctx.ExecMode() != sdk.ExecModeFinalize || ctx.BlockHeight() <= 0 ||
		validator == (common.Address{}) || percentage == 0 || percentage > 100 {
		return errors.New("Master penalty requires finalized block, validator, approved percentage, supply and reconciliation")
	}
	child, write := ctx.CacheContext()
	source, err := e.auth.AuthenticateStakeProfile(child)
	if err != nil {
		return err
	}
	sender := masterPenaltySender()
	if err := e.requireInert(child, sender); err != nil {
		return err
	}
	state, err := e.read(child, e.roles.MasterValidator, e.master, "getValidatorState", 3*common.HashLength, validator)
	if err != nil {
		return err
	}
	status := common.BytesToHash(state[:common.HashLength])
	paused := common.BytesToHash(state[common.HashLength : 2*common.HashLength])
	if (status != smallWord(1) && status != smallWord(2)) || (paused != (common.Hash{}) && (!historical || paused != smallWord(1))) {
		if !historical {
			return errors.New("Master penalty requires an unpaused candidate or approved validator")
		}
		return errors.New("historical Master penalty requires an eligible candidate or approved validator")
	}
	proof.BeforeCursor = common.BytesToHash(state[2*common.HashLength:])
	next := new(big.Int).Add(proof.BeforeCursor.Big(), big.NewInt(1))
	if next.BitLen() > 256 {
		return errors.New("Master penalty count exceeds uint256")
	}
	proof.AfterCursor = common.BigToHash(next)
	before, err := e.readMasterPenaltyBalances(child, validator, nativeSupply)
	if err != nil {
		return err
	}
	data, err := e.packMasterPenalty(proof)
	if err != nil {
		return err
	}
	authorized := child.WithValue(masterPenaltyKey{}, masterPenaltyCall{executor: e, height: child.BlockHeight(), proof: proof})
	result, err := e.invokePenalty(authorized, sender, e.roles.MasterValidator, data)
	if err != nil {
		return err
	}
	if len(result.Ret) != 0 {
		return errors.New("Master penalty returned unexpected data")
	}
	receipt := &ethtypes.Receipt{Status: ethtypes.ReceiptStatusSuccessful, Logs: evmtypes.LogsToEthereum(result.Logs)}
	if err := e.verifyMasterPenaltyLogs(receipt, status, paused == smallWord(1), proof); err != nil {
		return err
	}
	afterStatus, err := e.verifyMasterPenaltyAppend(child, proof)
	if err != nil {
		return err
	}
	if afterStatus != status {
		return errors.New("Master penalty changed the validator status")
	}
	after, err := e.readMasterPenaltyBalances(child, validator, nativeSupply)
	if err != nil {
		return err
	}
	if before.del != after.del || before.wdel != after.wdel || before.wdelSupply != after.wdelSupply ||
		!before.bankSupply.Equal(after.bankSupply) {
		return errors.New("Master penalty announcement changed native DEL or WDEL")
	}
	scope := &penaltySourceScope{executor: e, height: child.BlockHeight(), validator: validator, percentage: percentage, infractionHeight: proof.InfractionHeight, active: true}
	defer func() { scope.active = false }()
	if err := reconcile(child.WithValue(penaltySourceKey{}, scope), proof); err != nil {
		return fmt.Errorf("reconcile announced Master penalty: %w", err)
	}
	scope.active = false
	if err := e.confirmPenaltySource(child, &source); err != nil {
		return err
	}
	write()
	return nil
}

type masterPenaltyBalances struct {
	del, wdel  [5]common.Hash
	wdelSupply common.Hash
	bankSupply sdkmath.Int
}

func (e *Executor) readMasterPenaltyBalances(ctx sdk.Context, validator common.Address,
	nativeSupply func(sdk.Context) sdkmath.Int,
) (masterPenaltyBalances, error) {
	var balances masterPenaltyBalances
	for i, account := range [...]common.Address{validator, masterPenaltySender(), e.roles.MasterValidator, e.roles.Gateway, e.roles.WrappedDEL} {
		del := e.evm.GetBalance(ctx, account)
		if del == nil {
			return balances, errors.New("Master penalty cannot read native DEL balance")
		}
		balances.del[i] = common.BigToHash(del.ToBig())
		wdel, err := e.read(ctx, e.roles.WrappedDEL, e.wrapper, "balanceOf", common.HashLength, account)
		if err != nil {
			return balances, err
		}
		balances.wdel[i] = common.BytesToHash(wdel)
	}
	supply, err := e.read(ctx, e.roles.WrappedDEL, e.wrapper, "totalSupply", common.HashLength)
	if err != nil {
		return balances, err
	}
	balances.wdelSupply = common.BytesToHash(supply)
	balances.bankSupply = nativeSupply(ctx)
	if balances.bankSupply.IsNil() || balances.bankSupply.IsNegative() {
		return balances, errors.New("Master penalty requires valid native DEL supply")
	}
	return balances, nil
}

func (e *Executor) verifyMasterPenaltyState(ctx sdk.Context, validator common.Address, after common.Hash) (common.Hash, error) {
	state, err := e.read(ctx, e.roles.MasterValidator, e.master, "getValidatorState", 3*common.HashLength, validator)
	if err != nil {
		return common.Hash{}, err
	}
	status := common.BytesToHash(state[:common.HashLength])
	if (status != smallWord(1) && status != smallWord(2)) ||
		common.BytesToHash(state[common.HashLength:2*common.HashLength]) != smallWord(1) ||
		common.BytesToHash(state[2*common.HashLength:]) != after {
		return common.Hash{}, errors.New("penalty requires a paused validator and exactly one pending MasterValidator entry")
	}
	return status, nil
}

func (e *Executor) verifyMasterPenaltyAppend(ctx sdk.Context, proof MasterPenaltyProof) (common.Hash, error) {
	if proof.InfractionHeight == 0 {
		return e.verifyAnnouncedPenalty(ctx, proof.Validator, proof.BeforeCursor, proof.AfterCursor, proof.Percentage)
	}
	status, err := e.verifyMasterPenaltyState(ctx, proof.Validator, proof.AfterCursor)
	if err != nil {
		return common.Hash{}, err
	}
	words, err := e.read(ctx, e.roles.MasterValidator, e.master, "getDuplicateVotePenalty", 2*common.HashLength, proof.Validator, proof.BeforeCursor.Big())
	if err != nil {
		return common.Hash{}, err
	}
	if common.BytesToHash(words[:common.HashLength]) != common.BigToHash(big.NewInt(proof.InfractionHeight)) ||
		common.BytesToHash(words[common.HashLength:]) != smallWord(uint8(proof.Percentage)) {
		return common.Hash{}, errors.New("historical Master penalty does not match the approved height and percentage")
	}
	return status, nil
}

func (e *Executor) verifyMasterPenaltyLogs(receipt *ethtypes.Receipt, status common.Hash, alreadyPaused bool, proof MasterPenaltyProof) error {
	markers, err := e.completions(receipt)
	if err != nil {
		return err
	}
	wantCount := 2
	if alreadyPaused {
		wantCount = 1
	}
	if len(markers) != 0 || len(receipt.Logs) != wantCount {
		return errors.New("unexpected Master penalty log count")
	}
	identity := common.BytesToHash(proof.Validator[:])
	if !alreadyPaused {
		paused := smallWord(1)
		log := receipt.Logs[0]
		if log.Address != e.roles.MasterValidator || len(log.Topics) != 2 || log.Topics[0] != e.master.Events["ValidatorUpdated"].ID ||
			log.Topics[1] != identity || !bytes.Equal(log.Data, append(status.Bytes(), paused[:]...)) {
			return errors.New("Master penalty log does not match the exact pause")
		}
	}
	topics := []common.Hash{e.master.Events["ValidatorPenalty"].ID, identity}
	if proof.InfractionHeight != 0 {
		topics = []common.Hash{e.master.Events["ValidatorDuplicateVotePenalty"].ID, identity,
			proof.BeforeCursor, common.BigToHash(big.NewInt(proof.InfractionHeight))}
	}
	amount := smallWord(uint8(proof.Percentage))
	log := receipt.Logs[wantCount-1]
	if log.Address != e.roles.MasterValidator || !slices.Equal(log.Topics, topics) || !bytes.Equal(log.Data, amount[:]) {
		return errors.New("Master penalty log does not match the exact append")
	}
	return nil
}
